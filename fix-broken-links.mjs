#!/usr/bin/env node
/**
 * fix-broken-links.mjs
 *
 * Scans all published Markdown files in content/, finds wikilinks ([[...]]) that
 * point to non-existent pages, and strips them to plain text.
 *
 * Usage:
 *   node fix-broken-links.mjs           # dry-run (shows what would change)
 *   node fix-broken-links.mjs --fix     # actually write changes
 */

import fs from "node:fs"
import path from "node:path"
import matter from "gray-matter"

const CONTENT_DIR = path.resolve("content")
const DRY_RUN = !process.argv.includes("--fix")

// ── Quartz-compatible slug helpers ──────────────────────────────────────────

function sluggify(s) {
  return s
    .split("/")
    .map((seg) =>
      seg
        .replace(/\s/g, "-")
        .replace(/&/g, "-and-")
        .replace(/%/g, "-percent")
        .replace(/\?/g, "")
        .replace(/#/g, ""),
    )
    .join("/")
    .replace(/\/$/, "")
}

function filePathToSlug(fp) {
  // strip .md extension and sluggify
  const withoutExt = fp.replace(/\.md$/, "")
  let slug = sluggify(withoutExt)
  if (slug.endsWith("_index")) slug = slug.replace(/_index$/, "index")
  return slug
}

function simplifySlug(slug) {
  let res = slug
  // strip trailing "index"
  if (res === "index") return "/"
  if (res.endsWith("/index")) res = res.slice(0, -"/index".length)
  // strip leading/trailing slashes
  res = res.replace(/^\/+/, "").replace(/\/+$/, "")
  return res || "/"
}

// ── Collect all .md files recursively ───────────────────────────────────────

function walkDir(dir) {
  const results = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      // skip ignored directories
      if (["private", "templates", ".obsidian"].includes(entry.name)) continue
      if (entry.name === "drafts") continue
      results.push(...walkDir(full))
    } else if (entry.name.endsWith(".md")) {
      results.push(full)
    }
  }
  return results
}

// ── Build published slug index ──────────────────────────────────────────────

const allFiles = walkDir(CONTENT_DIR)
const publishedSlugs = new Set()   // SimpleSlug set
const publishedFileNames = new Map() // fileName → [simpleSlug, ...]

for (const filePath of allFiles) {
  const raw = fs.readFileSync(filePath, "utf-8")
  let fm
  try {
    fm = matter(raw)
  } catch {
    continue
  }

  if (!fm.data.publish) continue

  const rel = path.relative(CONTENT_DIR, filePath)
  const fullSlug = filePathToSlug(rel)
  const simple = simplifySlug(fullSlug)
  publishedSlugs.add(simple)

  // index by file name (last segment) for "shortest" resolution
  const fileName = simple.split("/").at(-1)
  if (fileName) {
    if (!publishedFileNames.has(fileName)) publishedFileNames.set(fileName, [])
    publishedFileNames.get(fileName).push(simple)
  }
}

// Also add folder slugs (auto-generated by FolderPage emitter)
for (const slug of [...publishedSlugs]) {
  const parts = slug.split("/")
  for (let i = 1; i < parts.length; i++) {
    publishedSlugs.add(parts.slice(0, i).join("/"))
  }
}

// ── Resolve a wikilink target to check if it exists ─────────────────────────

function resolveTarget(linkTarget, sourceSlug) {
  // Strip anchor (#heading)
  let target = linkTarget.split("#")[0].trim()
  if (!target) return true // anchor-only link like [[#heading]]

  // Sluggify the target the same way Quartz does
  const slugged = sluggify(target)
  const simplified = simplifySlug(slugged)

  // "shortest" strategy: match by file name first
  const fileName = simplified.split("/").at(-1)
  if (fileName) {
    const matches = publishedFileNames.get(fileName) ?? []
    if (matches.length === 1) return true   // unique match
    if (matches.length > 1) return true      // ambiguous but exists
  }

  // Fall back to absolute path match
  if (publishedSlugs.has(simplified)) return true

  // Try with source-relative resolution
  if (!simplified.includes("/") && sourceSlug) {
    const sourceDir = sourceSlug.includes("/")
      ? sourceSlug.split("/").slice(0, -1).join("/")
      : ""
    if (sourceDir) {
      const absolute = sourceDir + "/" + simplified
      if (publishedSlugs.has(absolute)) return true
    }
  }

  return false
}

// ── Wikilink regex ──────────────────────────────────────────────────────────
// Matches [[target]] and [[target|alias]], but NOT ![[embeds]]
// Negative lookbehind (?<!!) avoids image/file embeds
const WIKILINK_RE = /(?<!!)\[\[([^\]]+?)\]\]/g

function findPipeSeparator(match) {
  // In table cells, Obsidian escapes pipe as \|
  // Find the FIRST unescaped | (not preceded by \)
  for (let i = 0; i < match.length; i++) {
    if (match[i] === "|" && (i === 0 || match[i - 1] !== "\\")) {
      return i
    }
  }
  // Also accept \| as pipe separator (table context)
  const escapedIdx = match.indexOf("\\|")
  if (escapedIdx !== -1) return escapedIdx
  return -1
}

function getDisplayText(match) {
  // match is the content inside [[ ]]
  const pipeIdx = findPipeSeparator(match)
  if (pipeIdx !== -1) {
    // [[target|alias]] or [[target\|alias]] → show alias
    const afterPipe = match[pipeIdx] === "\\" ? pipeIdx + 2 : pipeIdx + 1
    return match.slice(afterPipe).trim()
  }
  // [[target#heading]] → show target (without heading)
  const hashIdx = match.indexOf("#")
  if (hashIdx !== -1) {
    const before = match.slice(0, hashIdx).trim()
    return before || match.slice(hashIdx + 1).trim()
  }
  // [[target]] → show target
  return match.trim()
}

function getLinkTarget(match) {
  const pipeIdx = findPipeSeparator(match)
  let raw = pipeIdx !== -1 ? match.slice(0, pipeIdx) : match
  // Strip trailing backslash from table-escaped pipes
  raw = raw.replace(/\\$/, "")
  return raw.trim()
}

// ── Process each published file ─────────────────────────────────────────────

let totalFixed = 0
let filesModified = 0
const report = []

for (const filePath of allFiles) {
  const raw = fs.readFileSync(filePath, "utf-8")
  let fm
  try {
    fm = matter(raw)
  } catch {
    continue
  }
  if (!fm.data.publish) continue

  const rel = path.relative(CONTENT_DIR, filePath)
  const fullSlug = filePathToSlug(rel)
  const sourceSlug = simplifySlug(fullSlug)

  let content = raw
  let fileFixCount = 0
  const fileReport = []

  content = content.replace(WIKILINK_RE, (fullMatch, inner) => {
    const target = getLinkTarget(inner)
    if (resolveTarget(target, sourceSlug)) {
      return fullMatch // link is valid, keep it
    }

    // Skip if inner content itself contains [[ (malformed/nested wikilink)
    if (inner.includes("[[")) {
      fileReport.push({ target, display: "(skipped — malformed nested wikilink)" })
      return fullMatch
    }

    // Broken link → replace with plain text
    const display = getDisplayText(inner)
    fileFixCount++
    fileReport.push({ target, display })
    return display
  })

  if (fileFixCount > 0) {
    totalFixed += fileFixCount
    filesModified++
    report.push({ file: rel, fixes: fileReport })

    if (!DRY_RUN) {
      fs.writeFileSync(filePath, content, "utf-8")
    }
  }
}

// ── Report ──────────────────────────────────────────────────────────────────

if (report.length === 0) {
  console.log("\n✅ No broken wikilinks found.\n")
} else {
  console.log(
    `\n${DRY_RUN ? "🔍 DRY RUN — " : "✏️  "}${totalFixed} broken wikilink(s) in ${filesModified} file(s)${DRY_RUN ? " (use --fix to apply)" : " fixed"}:\n`,
  )
  for (const { file, fixes } of report) {
    console.log(`  📄 ${file}`)
    for (const { target, display } of fixes) {
      console.log(`     [[${target}]] → ${display}`)
    }
  }
  console.log()
}
